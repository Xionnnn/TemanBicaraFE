-- One-time alignment of the inspected empty public schema with the Cold ERD.
-- The single DO statement rolls back on any failed precondition or assertion.
DO $migration$
DECLARE
  actual_tables text[];
BEGIN
  PERFORM set_config('lock_timeout', '5s', true);
  PERFORM set_config('search_path', 'pg_catalog, public', true);

  SELECT array_agg(table_name::text ORDER BY table_name)
    INTO actual_tables
    FROM information_schema.tables
    WHERE table_schema = 'public' AND table_type = 'BASE TABLE';

  IF actual_tables IS DISTINCT FROM ARRAY[
    'class_rooms', 'class_rooms_students', 'class_rooms_teachers',
    'dictionaries', 'dictionaries_assets', 'event_logs', 'roles', 'sessions', 'users'
  ]::text[] THEN
    RAISE EXCEPTION 'Unexpected public tables; inspect the database before applying this script.';
  END IF;

  LOCK TABLE public.class_rooms, public.class_rooms_students,
    public.class_rooms_teachers, public.dictionaries, public.dictionaries_assets,
    public.event_logs, public.roles, public.sessions, public.users
    IN ACCESS EXCLUSIVE MODE;

  IF EXISTS (
    SELECT 1 FROM public.class_rooms
    UNION ALL SELECT 1 FROM public.class_rooms_students
    UNION ALL SELECT 1 FROM public.class_rooms_teachers
    UNION ALL SELECT 1 FROM public.dictionaries
    UNION ALL SELECT 1 FROM public.dictionaries_assets
    UNION ALL SELECT 1 FROM public.event_logs
    UNION ALL SELECT 1 FROM public.roles
    UNION ALL SELECT 1 FROM public.sessions
    UNION ALL SELECT 1 FROM public.users
  ) THEN
    RAISE EXCEPTION 'This script requires empty tables; existing records need a data-preserving migration.';
  END IF;

  ALTER TABLE public.class_rooms_students RENAME COLUMN studentsid TO studentid;
  ALTER TABLE public.class_rooms_students
    RENAME CONSTRAINT class_rooms_students_studentsid_fkey
    TO class_rooms_students_studentid_fkey;

  ALTER TABLE public.class_rooms_students
    ADD COLUMN joined_at timestamp without time zone NOT NULL
      DEFAULT (now() AT TIME ZONE 'utc');
  ALTER TABLE public.class_rooms_teachers
    ADD COLUMN joined_at timestamp without time zone NOT NULL
      DEFAULT (now() AT TIME ZONE 'utc');

  ALTER TABLE public.users
    ADD COLUMN rolesid bigint NOT NULL,
    ADD CONSTRAINT users_rolesid_fkey FOREIGN KEY (rolesid) REFERENCES public.roles(id);

  CREATE TABLE public.assets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_name character varying NOT NULL,
    default_name character varying NOT NULL,
    created_at timestamp without time zone NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    updated_at timestamp without time zone NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    usersid integer,
    source_type character varying NOT NULL,
    CONSTRAINT assets_usersid_fkey FOREIGN KEY (usersid) REFERENCES public.users(id),
    CONSTRAINT assets_source_type_check CHECK (source_type IN ('builtin', 'custom')),
    CONSTRAINT assets_owner_check CHECK (
      (source_type = 'builtin' AND usersid IS NULL)
      OR (source_type = 'custom' AND usersid IS NOT NULL)
    )
  );

  ALTER TABLE public.sessions ALTER COLUMN usersid SET NOT NULL;
  ALTER TABLE public.event_logs
    ALTER COLUMN sessionsid SET NOT NULL,
    ADD COLUMN received_at timestamp without time zone NOT NULL
      DEFAULT (now() AT TIME ZONE 'utc'),
    DROP COLUMN asset_path;

  DROP TABLE public.dictionaries_assets;
  DROP TABLE public.dictionaries;

  IF EXISTS (
    WITH expected(table_name, column_names) AS (
      VALUES
        ('class_rooms', ARRAY['class_name', 'created_at', 'id', 'updated_at']),
        ('class_rooms_students', ARRAY['class_roomsid', 'joined_at', 'studentid']),
        ('class_rooms_teachers', ARRAY['class_roomsid', 'joined_at', 'teachersid']),
        ('users', ARRAY['created_at', 'email', 'id', 'password', 'rolesid', 'updated_at', 'user_name']),
        ('roles', ARRAY['created_at', 'id', 'role_name', 'updated_at']),
        ('assets', ARRAY['asset_name', 'created_at', 'default_name', 'id', 'source_type', 'updated_at', 'usersid']),
        ('sessions', ARRAY['created_at', 'ended_at', 'id', 'started_at', 'updated_at', 'usersid']),
        ('event_logs', ARRAY['created_at', 'event_type', 'id', 'payload', 'received_at', 'sessionsid', 'updated_at'])
    ), actual AS (
      SELECT table_name::text, array_agg(column_name::text ORDER BY column_name) AS column_names
      FROM information_schema.columns
      WHERE table_schema = 'public'
      GROUP BY table_name
    )
    SELECT 1 FROM expected FULL JOIN actual USING (table_name)
    WHERE expected.column_names IS DISTINCT FROM actual.column_names
  ) THEN
    RAISE EXCEPTION 'Cold ERD table/column verification failed; all changes are rolled back.';
  END IF;
END;
$migration$;
